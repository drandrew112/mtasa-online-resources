// Generates docs/tools.md from the tool definitions: node scripts/gen-tool-docs.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { zodToJsonSchema } from 'zod-to-json-schema';
import { z } from 'zod';
import { TOOLS } from '../src/tools/registry.js';
import { MODULES, WORKFLOWS } from '../src/capabilities.js';
import '../src/server.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const lines = ['# MCP tool reference', '', '_Generated by `npm run docs` from the tool definitions — do not edit by hand._', ''];
lines.push(`${TOOLS.length} tools in ${Object.keys(MODULES).length} modules. "probe" = needs a connected game client (partial = degrades without one).`, '');
for (const [mod, desc] of Object.entries(MODULES)) {
  const list = TOOLS.filter((t) => t.module === mod);
  if (!list.length) continue;
  lines.push(`## ${mod}`, '', desc, '');
  for (const t of list) {
    lines.push(`### \`${t.name}\` — ${t.title}`, '');
    lines.push(`**${t.kind === 'read' ? 'read-only' : 'mutating'}** · probe: ${t.needsProbe === true ? 'required' : t.needsProbe === 'partial' ? 'partial' : 'no'}`, '');
    lines.push(t.description, '');
    const schema = zodToJsonSchema(z.object(t.input || {}), { $refStrategy: 'none' });
    const props = schema.properties || {};
    if (Object.keys(props).length) {
      lines.push('| parameter | type | required | description |', '|---|---|---|---|');
      for (const [k, v] of Object.entries(props)) {
        const type = v.type || (v.anyOf ? v.anyOf.map((x) => x.type || 'object').join(' \| ') : v.enum ? 'enum' : 'any');
        const en = v.enum ? ` (${v.enum.join(', ')})` : '';
        lines.push(`| ${k} | ${type}${en} | ${(schema.required || []).includes(k) ? 'yes' : ''} | ${(v.description || '').replace(/\|/g, '\|')} |`);
      }
      lines.push('');
    }
    if (t.returns) lines.push(`Returns: ${t.returns.join('; ')}`, '');
    if (t.sideEffects) lines.push(`Side effects: ${t.sideEffects}`, '');
    if (t.limitations) lines.push(`Limitations: ${t.limitations.join(' ')}`, '');
    if (t.related) lines.push(`Related: ${t.related.join(', ')}`, '');
  }
}
lines.push('## Workflows', '');
for (const w of WORKFLOWS) lines.push(`- **${w.name}** — ${w.goal}: ${w.steps.join(' → ')}`);
fs.writeFileSync(path.resolve(here, '../../docs/tools.md'), lines.join('\n') + '\n');
console.log('docs/tools.md written');
