# navmesh pedestrian path graph:   python tools/build_peds.py ["C:/Games/GTA San Andreas"]   (after build_roads.py)
# Input: GTA data/Paths/NODES*.DAT ped nodes (37650 nodes, 40343 links, crossing / ped light flags per link),
#        data/runtime/roads.nav (lanes + signal groups)
# Output: data/runtime/peds.nav, data/build/peds_report.json
# The old npchlc_traffic ped network (source/npchlc_traffic/paths) is a resampled subset of the same GTA data
# (11520 nodes, median 1.6 m from a GTA node), so it is not used.
import json, math, collections, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gta_paths as GP

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GTA = sys.argv[1] if len(sys.argv) > 1 else 'C:/Games/GTA San Andreas'
RUNTIME = os.path.join(ROOT, 'data', 'runtime')
BUILD = os.path.join(ROOT, 'data', 'build')
SIDEWALK_DIST = 6.0     # edge of the carriageway -> sidewalk if the ped edge runs this close
LANE_HALF = 2.5
SIGNAL_RADIUS = 45.0    # a lit crossing belongs to the signal group this close

def r2(x): return round(x, 2)
P = GP.load(GTA)['ped']

# ---------------------------------------------------------------- road lanes + signal groups
lanes = []; groups = []
for line in open(os.path.join(RUNTIME, 'roads.nav')):
    p = line.split()
    if not p: continue
    if p[0] == 'A':
        v = list(map(float, p[10:16])); lanes.append(v)
    elif p[0] == 'S':
        groups.append((int(p[1]), float(p[2]), float(p[3]), float(p[4]), p[5]))
CELL = 25
lgrid = collections.defaultdict(list)
for i, v in enumerate(lanes):
    for gx in range(int(min(v[0], v[3]) // CELL), int(max(v[0], v[3]) // CELL) + 1):
        for gy in range(int(min(v[1], v[4]) // CELL), int(max(v[1], v[4]) // CELL) + 1):
            lgrid[(gx, gy)].append(i)
def seg_dist(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay; L2 = dx * dx + dy * dy or 1e-9
    u = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L2))
    return math.hypot(px - ax - dx * u, py - ay - dy * u), u
def road_edge_dist(x, y, z):
    best = 1e9
    gx, gy = int(x // CELL), int(y // CELL)
    for i in range(gx - 1, gx + 2):
        for j in range(gy - 1, gy + 2):
            for li in lgrid.get((i, j), ()):
                v = lanes[li]
                d, u = seg_dist(x, y, v[0], v[1], v[3], v[4])
                lz = v[2] + (v[5] - v[2]) * u
                if abs(lz - z) > 4: continue
                best = min(best, d - LANE_HALF)
    return best

# ---------------------------------------------------------------- graph
ids = {g: i + 1 for i, g in enumerate(sorted(P))}
edges = {}
for g, n in P.items():
    for (o, _ln, xf, _nav) in n['links']:
        if o not in P or o == g: continue
        k = (min(g, o), max(g, o))
        e = edges.setdefault(k, dict(x=0))
        e['x'] |= xf
KIND = dict(sidewalk=1, path=2, crossing=3, lit=4)
kinds = collections.Counter(); klen = collections.Counter()
lit_nogroup = 0
out = ["# navmesh peds v1 - GENERATED by tools/build_peds.py from the GTA ped path nodes (NODES*.DAT)",
       "# N id x y z width flood flags        (width m; flood = GTA flood-fill area; flags: GTA node flags >> 4)",
       "# E a b kind length group phase       (kind: 1 sidewalk 2 path 3 crossing 4 crossing with ped light;",
       "#                                      group: signal group of roads.nav, 0 = none (global cycle); phase: the car phase that runs along the crossing)"]
for g in sorted(P):
    n = P[g]
    out.append(f"N {ids[g]} {r2(n['x'])} {r2(n['y'])} {r2(n['z'])} {r2(n['width'])} {n['flood']} {n['flags'] >> 4}")
for (a, b), e in sorted(edges.items()):
    A, B = P[a], P[b]
    L = math.dist((A['x'], A['y'], A['z']), (B['x'], B['y'], B['z']))
    group = phase = 0
    if e['x'] & GP.X_ROADCROSS:
        kind = 'lit' if e['x'] & GP.X_PEDLIGHT else 'crossing'
        if kind == 'lit':
            mx, my = (A['x'] + B['x']) / 2, (A['y'] + B['y']) / 2
            best = None
            for gid, gx, gy, gz, ph in groups:
                d = math.hypot(gx - mx, gy - my)
                if d < SIGNAL_RADIUS and (best is None or d < best[0]): best = (d, gid)
            if best: group = best[1]
            else: lit_nogroup += 1   # ped light without car signals nearby: follows the global light cycle
            # peds walk along the cars of the same axis: 1 = north-south, 2 = east-west
            phase = 1 if abs(B['y'] - A['y']) >= abs(B['x'] - A['x']) else 2
    else:
        # sample the edge: sidewalk when most of it runs next to a carriageway
        near = 0; samples = max(2, int(L // 8) + 1)
        for s in range(samples):
            t = (s + 0.5) / samples
            if road_edge_dist(A['x'] + (B['x'] - A['x']) * t, A['y'] + (B['y'] - A['y']) * t, A['z'] + (B['z'] - A['z']) * t) <= SIDEWALK_DIST: near += 1
        kind = 'sidewalk' if near * 2 >= samples else 'path'
    kinds[kind] += 1; klen[kind] += L
    out.append(f"E {ids[a]} {ids[b]} {KIND[kind]} {r2(L)} {group} {phase}")
os.makedirs(RUNTIME, exist_ok=True); os.makedirs(BUILD, exist_ok=True)
open(os.path.join(RUNTIME, 'peds.nav'), 'w', newline='\n').write('\n'.join(out) + '\n')

# components
adj = collections.defaultdict(list)
for a, b in edges: adj[a].append(b); adj[b].append(a)
seen = set(); comps = []
for g in P:
    if g in seen: continue
    st = [g]; seen.add(g); c = 0
    while st:
        x = st.pop(); c += 1
        for y in adj[x]:
            if y not in seen: seen.add(y); st.append(y)
    comps.append(c)
comps.sort(reverse=True)
report = dict(nodes=len(P), edges=len(edges), kinds=dict(kinds), km={k: round(v / 1000, 1) for k, v in klen.items()},
              litWithoutSignalGroup=lit_nogroup, components=len(comps), largestComponents=comps[:10],
              isolatedNodes=sum(1 for c in comps if c == 1))
json.dump(report, open(os.path.join(BUILD, 'peds_report.json'), 'w'), indent=1)
print(json.dumps(report))
