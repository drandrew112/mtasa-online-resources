#!/usr/bin/env python3
"""Builds osa.js and osa.css from src/. Run after every edit:  python tools/build.py

Why a build: pages load ONE /web_api/osa.js and ONE /web_api/osa.css (in game from CEF, over HTTP
inlined by server/page.lua), so the sources are kept in small modules and joined here.
The js modules are fragments of ONE closure (they share `OSA`, `create`, ...), in this order."""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

JS = [  # (file, what it provides)
    ('core',      'OSA object, helpers (arr / esc / clean / store / ready), in-page anchors'),
    ('time',      'hhmm / clock / delay / age, the server clock (OSA.time)'),
    ('transport', 'OSA.api: http="true" exports over HTTP or the in-game bridge'),
    ('poll',      'OSA.poll: self-scheduling poll loop'),
    ('toast',     'OSA.toast'),
    ('overlays',  'OSA.ui: context menu, tooltip, form / confirm dialogs'),
    ('dropdown',  'select.osa-select -> in-page dropdown (native popups do not show in game)'),
    ('map',       'OSA.Map: pan / zoom map on the v_radar bigmap + the OpenSanAndreas credit'),
]
CSS = [
    ('base',      'variables, reset'),
    ('topbar',    'top bar, stats, clock'),
    ('layout',    'main area, panels, lists, tabs'),
    ('controls',  'buttons, badges, pills, key/value, tables'),
    ('login',     'login screen'),
    ('map',       'map, markers, legend, credit'),
    ('overlays',  'context menu, tooltip, modal, toasts'),
    ('dropdown',  'custom select dropdown'),
]

def read(kind, name):
    with open(os.path.join(ROOT, 'src', kind, name + '.' + kind), encoding='utf-8') as f:
        return f.read().rstrip('\n') + '\n'

def toc(items):
    return ''.join('   %-10s %s\n' % (n, d) for n, d in items)

def build():
    head = ('/* ============================================================================\n'
            '   OSA web toolkit - shared %s (web_api/%s)        Provided by OpenSanAndreas\n'
            '   GENERATED by tools/build.py from src/%s/ - edit the modules, not this file.\n'
            '   Modules:\n%s'
            '   ========================================================================== */\n')
    js = head % ('script', 'osa.js', 'js', toc(JS))
    js += "(function () {\n    'use strict';\n    if (window.OSA) return;\n\n"
    js += '\n'.join(read('js', n) for n, _ in JS)
    js += '})();\n'
    css = head % ('styles', 'osa.css', 'css', toc(CSS)) + '\n' + '\n'.join(read('css', n) for n, _ in CSS)
    for name, text in (('osa.js', js), ('osa.css', css)):
        with open(os.path.join(ROOT, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(name, len(text.splitlines()), 'lines')

if __name__ == '__main__':
    build()
